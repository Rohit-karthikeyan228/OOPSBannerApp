/**
 * OOPSBannerApp
 *
 * UC3 - Prints OOPS banner using String.join()
 * Refactored for better memory efficiency.
 *
 * @author Rohit
 * @version 3.0
 */
public class OOPSBannerApp {

    public static void main(String[] args) {

        System.out.println(String.join("",
                "  *****   ",
                "  *****   ",
                " *******  ",
                "  *****   "
        ));

        System.out.println(String.join("",
                " *     *  ",
                " *     *  ",
                " *     *  ",
                " *     *  "
        ));

        System.out.println(String.join("",
                " *     *  ",
                " *     *  ",
                " *     *  ",
                " *        "
        ));

        System.out.println(String.join("",
                " *     *  ",
                " *     *  ",
                " *******  ",
                "  *****   "
        ));

        System.out.println(String.join("",
                " *     *  ",
                " *     *  ",
                " *        ",
                "       *  "
        ));

        System.out.println(String.join("",
                " *     *  ",
                " *     *  ",
                " *        ",
                " *     *  "
        ));

        System.out.println(String.join("",
                "  *****   ",
                "  *****   ",
                " *        ",
                "  *****   "
        ));
    }
}